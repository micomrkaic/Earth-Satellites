#!/usr/bin/env python3
"""
gen_map_data.py — generate map_data.h from Natural Earth data (via world-atlas npm).

Downloads the world-atlas@2.0.2 npm package (tarball ~750 KB) which contains
Natural Earth 1:50m country boundaries as TopoJSON.

Decodes the TopoJSON arc format and splits arcs into:
  • coast  — arcs that border the ocean (used by the unified 'land' polygon)
  • border — arcs shared between two countries (internal land borders)

Outputs map_data.h with flat C float arrays ready for direct inclusion.
"""

import json, os, sys, tarfile, io, urllib.request

NPM_URL = "https://registry.npmjs.org/world-atlas/-/world-atlas-2.0.2.tgz"
TARBALL = "world-atlas-2.0.2.tgz"
TOPO_PATH = "package/countries-50m.json"   # use 50m for good detail
OUT = "map_data.h"

# ── fetch tarball ──────────────────────────────────────────────────────────
if not os.path.exists(TARBALL):
    print(f"Downloading {NPM_URL} ...", end="", flush=True)
    try:
        urllib.request.urlretrieve(NPM_URL, TARBALL)
        print(f" done  ({os.path.getsize(TARBALL)//1024} KB)")
    except Exception as exc:
        print(f"\nERROR: {exc}", file=sys.stderr)
        sys.exit(1)
else:
    print(f"Using cached {TARBALL}")

# ── extract and parse TopoJSON ─────────────────────────────────────────────
print(f"Parsing {TOPO_PATH} ...")
with tarfile.open(TARBALL, "r:gz") as tf:
    member = tf.getmember(TOPO_PATH)
    topo = json.load(tf.extractfile(member))

scale     = topo["transform"]["scale"]
translate = topo["transform"]["translate"]
raw_arcs  = topo["arcs"]

# ── decode TopoJSON delta-encoded arcs to lon/lat ──────────────────────────
def decode_arc(raw):
    """Delta-decode one TopoJSON arc to [(lon, lat), ...] in degrees."""
    pts = []
    x, y = 0, 0
    for dx, dy in raw:
        x += dx
        y += dy
        pts.append((x * scale[0] + translate[0],
                    y * scale[1] + translate[1]))
    return pts

decoded = [decode_arc(a) for a in raw_arcs]

# ── collect arc indices used by a TopoJSON geometry ───────────────────────
def arc_indices(geom):
    """Return set of arc indices (always positive) referenced by a geometry."""
    idx = set()
    def walk(rings_or_polys):
        for item in rings_or_polys:
            if isinstance(item[0], list):   # nested (MultiPolygon)
                walk(item)
            else:                            # ring = list of arc refs
                for ref in item:
                    idx.add(ref if ref >= 0 else ~ref)
    g = geom.get("arcs", [])
    if geom["type"] == "Polygon":
        walk(g)
    elif geom["type"] == "MultiPolygon":
        walk(g)
    return idx

# ── identify coastline vs border arcs ─────────────────────────────────────
# 'land' object is a single merged polygon; its arcs bound the ocean → coastlines.
# Arcs used in 'countries' but NOT in 'land' are internal land borders.
land_geoms    = topo["objects"]["land"]["geometries"]
country_geoms = topo["objects"]["countries"]["geometries"]

land_arc_idx = set()
for g in land_geoms:
    land_arc_idx |= arc_indices(g)

country_arc_idx = set()
for g in country_geoms:
    country_arc_idx |= arc_indices(g)

coast_idx  = land_arc_idx
border_idx = country_arc_idx - land_arc_idx   # internal only

coast_lines  = [decoded[i] for i in sorted(coast_idx)]
border_lines = [decoded[i] for i in sorted(border_idx)]

print(f"  coastlines : {len(coast_lines):4d} arcs")
print(f"  borders    : {len(border_lines):4d} arcs")

# ── C array output ─────────────────────────────────────────────────────────
def write_layer(f, name, lines):
    all_pts, starts, lens = [], [], []
    for line in lines:
        if len(line) < 2:
            continue
        starts.append(len(all_pts))
        lens.append(len(line))
        all_pts.extend(line)
    n = len(starts)
    total = len(all_pts)
    print(f"  {name:8s}: {n:4d} polylines, {total:6d} points")

    f.write(f"/* {name}: {n} polylines, {total} points */\n")

    # Points: stored as interleaved float pairs lon,lat
    f.write(f"static const float {name}_pts[{total}][2] = {{\n")
    chunk = 4   # points per line for readability
    for i in range(0, total, chunk):
        seg = all_pts[i:i+chunk]
        f.write("    " + ", ".join(f"{{{p[0]:.4f}f,{p[1]:.4f}f}}" for p in seg) + ",\n")
    f.write("};\n")

    f.write(f"static const int {name}_start[{n}] = {{\n    ")
    f.write(", ".join(str(s) for s in starts))
    f.write("\n};\n")

    f.write(f"static const int {name}_len[{n}] = {{\n    ")
    f.write(", ".join(str(l) for l in lens))
    f.write("\n};\n")
    f.write(f"#define {name.upper()}_NPOLYS {n}\n\n")

print(f"Writing {OUT} ...")
with open(OUT, "w") as f:
    f.write("/* map_data.h — auto-generated by gen_map_data.py — do not edit\n")
    f.write("   Natural Earth 1:50m via world-atlas@2.0.2 (ISC licence)\n")
    f.write("   https://www.naturalearthdata.com  /  https://github.com/topojson/world-atlas */\n")
    f.write("#pragma once\n\n")
    write_layer(f, "coast",  coast_lines)
    write_layer(f, "border", border_lines)

sz = os.path.getsize(OUT)
print(f"Done — {OUT} is {sz//1024} KB, {sum(1 for _ in open(OUT))} lines")
